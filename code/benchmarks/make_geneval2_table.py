#!/usr/bin/env python3
"""Build the paper's GenEval 2 table from complete scores and cited comparisons.

    python benchmarks/make_geneval2_table.py
    python benchmarks/make_geneval2_table.py --generators klein dev qwenimage

Published numbers are pinned in geneval2/published_results.json. Our rows are
recomputed from all four samples; an incomplete arm fails before writing.
"""

import argparse
import json
import math
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE / "geneval2"
GENERATORS = {"klein": "FLUX.2-klein-9B", "dev": "FLUX.2-dev", "qwenimage": "Qwen-Image"}
ARMS = (("k3", "Kimi K3", "ours"),
        ("qwen38", "Qwen3.8-27B", "ours"),
        ("direct", "Direct (ours)", "baseline"))


def summarize(arm_dir, benchmark, samples=4):
    files = sorted(arm_dir.glob("sample_*.json"))
    expected = {f"sample_{s:02d}.json" for s in range(samples)}
    if {f.name for f in files} != expected:
        raise ValueError(f"{arm_dir}: expected exactly {samples} sample files")
    am, gm = [], []
    for path in files:
        rows = json.loads(path.read_text())
        if len(rows) != len(benchmark):
            raise ValueError(f"{path}: score rows do not match benchmark prompts")
        for scores, prompt in zip(rows, benchmark):
            if not scores or len(scores) != len(prompt["vqa_list"]):
                raise ValueError(f"{path}: score atoms do not match VQA questions")
            # The official scorer's float32 probability sums can exceed one
            # by ~1e-7. Validate with tolerance, keeping its values unchanged.
            if any(not math.isfinite(x) or x < 0 or x > 1 + 1e-6 for x in scores):
                raise ValueError(f"{path}: invalid probability")
            am.append(statistics.mean(scores))
            gm.append(0.0 if 0 in scores else statistics.geometric_mean(scores))
    return {"am": 100 * statistics.mean(am), "gm": 100 * statistics.mean(gm)}


def build_rows(scores_dir, benchmark, published, generators=("klein",)):
    rows = list(published["rows"])
    for generator in generators:
        for reasoner, method, style in ARMS:
            arm = f"{reasoner}-{generator}"
            rows.append({"method": method, "generator": GENERATORS[generator],
                         "style": style, **summarize(scores_dir / arm, benchmark)})
    return sorted(rows, key=lambda row: -row["gm"])


def render(rows):
    lines = [
        "% Generated by: python benchmarks/make_geneval2_table.py",
        r"\begin{table}[t]", r"\centering", r"\small",
        r"\resizebox{\columnwidth}{!}{%", r"\begin{tabular}{llrr}",
        r"\toprule", r"Method / Agent & Base generator & GM $\uparrow$ & AM $\uparrow$ \\",
        r"\midrule",
    ]
    for row in rows:
        method, generator = row["method"], row["generator"]
        gm, am = f"{row['gm']:.2f}", f"{row['am']:.2f}"
        if row.get("source"):
            marker = r"\dagger" if row["source"] == "epic" else r"\ddagger"
            method += "$^{" + marker + "}$"
        if row.get("style") == "ours":
            method, generator, gm, am = (r"\textbf{" + x + "}" for x in (method, generator, gm, am))
        elif row.get("style") == "baseline":
            generator = r"\textit{" + generator + "}"
        lines.append(f"{method} & {generator} & {gm} & {am}" + r" \\")
    lines += [
        r"\bottomrule", r"\end{tabular}%", "}",
        r"\caption{\draftON \textbf{GenEval 2 Results.} Soft-TIFA geometric (GM) and "
        r"arithmetic (AM) mean scores on a 0--100 scale, ordered by GM. "
        r"\textbf{Bold} rows use our agentic loop; \textit{italics} identify direct baselines. "
        r"All our configurations average four samples per prompt over all 800 prompts. "
        r"$\dagger$: published results from EPIC~\cite{mun2026epic}, Tables~1 and~6 ($T=0$). "
        r"$\ddagger$: published Soft-TIFA results from GenEval~2~\cite{kamath2025geneval2}, "
        r"Table~4 (original prompts). Published comparisons use different agent and compute "
        r"settings; our agent arms also allow FLUX.1-Fill inpainting. These are "
        r"cross-paper comparisons, with no official leaderboard ranks assigned.}",
        r"\label{tab:geneval2}", r"\end{table}",
    ]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=HERE.parent / "paper/tab/geneval2.tex")
    parser.add_argument("--scores", type=Path, default=DATA / "scores")
    parser.add_argument("--generators", nargs="+", choices=GENERATORS, default=["klein"])
    args = parser.parse_args()
    benchmark = [json.loads(line) for line in (DATA / "geneval2_data.jsonl").read_text().splitlines()
                 if line.strip()]
    published = json.loads((DATA / "published_results.json").read_text())
    rows = build_rows(args.scores, benchmark, published, args.generators)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(rows))
    print(f"Wrote {len(rows)} rows to {args.out}")


if __name__ == "__main__":
    main()
